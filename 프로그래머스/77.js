function solution(money) {
  // money 배열의 길이를 저장합니다
  const n = money.length;

  // 첫 번째 집을 털 경우의 최대 금액을 저장할 배열
  const dp1 = Array(n).fill(0);

  // 첫 번째 집을 털지 않을 경우의 최대 금액을 저장할 배열
  const dp2 = Array(n).fill(0);

  // 첫 번째 집을 털 경우, 첫 번째 집의 돈을 가져갑니다
  dp1[0] = money[0];

  // 두 번째 집까지 고려할 때, 첫 번째 집의 돈이 최대입니다 (두 번째 집은 못 털어요)
  dp1[1] = money[0];

  // 첫 번째 집을 털었으므로, 마지막 집은 털 수 없습니다 (n-1번째 집)
  // 그래서 n-2번째 집까지만 계산합니다
  for (let i = 2; i < n - 1; i++) {
    // 현재 집을 털지 않는 경우: dp1[i-1] (이전 집까지의 최대값)
    // 현재 집을 터는 경우: dp1[i-2] + money[i] (전전 집까지의 최대값 + 현재 집의 돈)
    // 두 경우 중 더 큰 값을 선택합니다
    dp1[i] = Math.max(dp1[i - 1], dp1[i - 2] + money[i]);
  }

  // 첫 번째 집을 털지 않는 경우, 첫 번째 집의 돈은 0입니다
  // dp2[0] = 0 (이미 0으로 초기화되어 있어서 따로 적지 않았어요)

  // 두 번째 집을 털면 두 번째 집의 돈을 가져갑니다
  dp2[1] = money[1];

  // 첫 번째 집을 털지 않았으므로, 마지막 집을 털 수 있습니다
  // 그래서 n-1번째 집(마지막 집)까지 계산합니다
  for (let i = 2; i < n; i++) {
    // 현재 집을 털지 않는 경우: dp2[i-1] (이전 집까지의 최대값)
    // 현재 집을 터는 경우: dp2[i-2] + money[i] (전전 집까지의 최대값 + 현재 집의 돈)
    // 두 경우 중 더 큰 값을 선택합니다
    dp2[i] = Math.max(dp2[i - 1], dp2[i - 2] + money[i]);
  }

  // 두 가지 경우(첫 집을 털거나 vs 첫 집을 털지 않거나) 중 더 큰 값을 답으로 반환합니다
  const answer = Math.max(dp1[n - 2], dp2[n - 1]);
  return answer;
}
